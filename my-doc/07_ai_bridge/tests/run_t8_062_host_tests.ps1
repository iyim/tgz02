# run_t8_062_host_tests.ps1 -- T8-06.2: behaviour test for the T6 entry-page
# protection fix (patch_entry / tg_hook_uninstall / tg_hook_install) and for the
# NLU stub page protection lifecycle (build_nlu_stub_page), plus every
# regression suite this round can touch.
#
#   powershell -ExecutionPolicy Bypass -File run_t8_062_host_tests.ps1
#
# The production functions are extracted VERBATIM from
# hook_agent/libtg_hook.c into tests/out/t8_062_prod_snippet.inc and driven by
# t8_062_t6_prot_test.c (fakes for fopen/mprotect/mmap/munmap/pthread_*).
# Every branch, including all failure paths, is executed for real -- the
# source-string assertions below are only a complement, never a substitute.
#
# NOTE: keep this file ASCII-only (PowerShell 5.1 reads a BOM-less file as ANSI).
$ErrorActionPreference = "Stop"

$Gcc = "C:\TDM-GCC-64\bin\gcc.exe"
if (-not (Test-Path $Gcc)) { throw "gcc not found: $Gcc" }

$Here = $PSScriptRoot
$Root = Split-Path $Here -Parent
$Android = Join-Path $Root "android"
$Ev = Join-Path $Root "evidence"
$Out = Join-Path $Here "out"
New-Item -ItemType Directory -Force $Out | Out-Null
New-Item -ItemType Directory -Force $Ev | Out-Null
Set-Location $Here

$Log = Join-Path $Ev "t8_062_host_test.log"
$script:Lines = New-Object System.Collections.Generic.List[string]
function Log([string]$s) { $script:Lines.Add($s); Write-Host $s }
$script:Fail = 0
function Fail([string]$why) { $script:Fail++; Log "FAIL $why" }
function Pass([string]$why) { Log "PASS $why" }

Log "# T8-06.2 host test log (T6 entry page protection + NLU stub page)"
Log "# host time: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
Log ""

# ---------------------------------------------------------- snippet extraction
$HookPath = Join-Path $Android "hook_agent\libtg_hook.c"
$src = Get-Content $HookPath

function Extract-Fn([string[]]$lines, [string]$sigRegex) {
    $start = -1
    for ($i = 0; $i -lt $lines.Length; $i++) {
        if ($lines[$i] -match $sigRegex) { $start = $i; break }
    }
    if ($start -lt 0) { return $null }
    $acc = @()
    for ($i = $start; $i -lt $lines.Length; $i++) {
        $acc += $lines[$i]
        if ($lines[$i] -eq '}') { break }
    }
    return $acc
}

$fnPage    = Extract-Fn $src '^static int page_prot\(uintptr_t page\)$'
$fnBegin   = Extract-Fn $src '^static int entry_begin_write\(const char \*what\)$'
$fnRestore = Extract-Fn $src '^static int entry_restore_prot\(const char \*what\)$'
$fnPatch   = Extract-Fn $src '^static int patch_entry\(void\)$'
$fnUninst  = Extract-Fn $src '^int tg_hook_uninstall\(void\)$'
$fnInst    = Extract-Fn $src '^int tg_hook_install\(void\)$'
$fnVerify  = Extract-Fn $src '^static int verify_entry_state\(void\)$'
$fnStub    = Extract-Fn $src '^static int build_nlu_stub_page\(uint32_t func, int \*err_out\)$'

Log "=== extract production functions from hook_agent/libtg_hook.c ==="
$wanted = @(
    @{ n = "page_prot()";             f = $fnPage },
    @{ n = "entry_begin_write()";     f = $fnBegin },
    @{ n = "entry_restore_prot()";    f = $fnRestore },
    @{ n = "patch_entry()";           f = $fnPatch },
    @{ n = "tg_hook_uninstall()";     f = $fnUninst },
    @{ n = "tg_hook_install()";       f = $fnInst },
    @{ n = "verify_entry_state()";    f = $fnVerify },
    @{ n = "build_nlu_stub_page()";   f = $fnStub }
)
foreach ($w in $wanted) {
    if ($null -eq $w.f) { Fail ($w.n + " not found in libtg_hook.c") }
    else { Log ("  ok  {0,-24} {1} lines" -f $w.n, $w.f.Count) }
}
if ($script:Fail -ne 0) {
    $script:Lines | Out-File -FilePath $Log -Encoding utf8
    throw "extraction failed; see $Log"
}

$snippet = @()
$snippet += "/* GENERATED by run_t8_062_host_tests.ps1 -- do not edit."
$snippet += " * Verbatim copy of eight functions from hook_agent/libtg_hook.c:"
$snippet += " *   page_prot(), entry_begin_write(), entry_restore_prot(), patch_entry(),"
$snippet += " *   tg_hook_uninstall(), tg_hook_install(), verify_entry_state(),"
$snippet += " *   build_nlu_stub_page()"
$snippet += " * Included by tests/t8_062_t6_prot_test.c together with host fakes so"
$snippet += " * every branch can be driven for real. */"
$snippet += ""
$snippet += $fnPage
$snippet += ""
$snippet += $fnBegin
$snippet += ""
$snippet += $fnRestore
$snippet += ""
$snippet += $fnPatch
$snippet += ""
$snippet += $fnUninst
$snippet += ""
$snippet += $fnVerify
$snippet += ""
$snippet += $fnInst
$snippet += ""
$snippet += $fnStub
$snippet += ""

$IncPath = Join-Path $Out "t8_062_prod_snippet.inc"
[System.IO.File]::WriteAllText($IncPath, (($snippet -join "`r`n") + "`r`n"),
    (New-Object System.Text.UTF8Encoding($false)))

# --------------------------------------------------------------------- build
Log ""
Log "=== build t8_062_t6_prot_test ==="
$Exe = Join-Path $Out "t8_062_t6_prot_test.exe"
$tSrc = Join-Path $Here "t8_062_t6_prot_test.c"
# native stderr must not be turned into a terminating error by Stop mode
$ErrorActionPreference = "Continue"
$build = & $Gcc -O2 -Wall -Wextra -std=gnu99 -o $Exe $tSrc 2>&1 | Out-String
$brc = $LASTEXITCODE
$ErrorActionPreference = "Stop"
if ($brc -ne 0) {
    ($build.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ }
    Fail "build failed: t8_062_t6_prot_test"
}
elseif ($build -match 'warning\s*:') {
    ($build.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ }
    Fail "compiler warnings in t8_062_t6_prot_test"
}
else { Pass "t8_062_t6_prot_test: 0 warning / 0 error" }

Log ""
Log "=== run t8_062_t6_prot_test ==="
if ($brc -eq 0) {
    $ErrorActionPreference = "Continue"
    $run = & $Exe 2>&1 | Out-String
    $rrc = $LASTEXITCODE
    $ErrorActionPreference = "Stop"
    ($run.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ }
    Log ("exit : " + $rrc)
    if ($run -notmatch 'pass=(\d+) fail=(\d+)') { Fail "t8_062_t6_prot_test: unreadable summary" }
    elseif ([int]$Matches[2] -ne 0) { Fail ("t8_062_t6_prot_test: " + $Matches[2] + " failing assertion(s)") }
    elseif ($rrc -ne 0) { Fail "t8_062_t6_prot_test: non-zero exit" }
    else { Pass ("t8_062_t6_prot_test: " + $Matches[1] + " assertions, 0 failures") }
}

# --------------------------------- complement: the extracted text is the fix
Log ""
Log "=== source assertions (only as a complement to the behaviour test) ==="

$pTxt = ($fnPatch -join "`n")
$uTxt = ($fnUninst -join "`n")
$rTxt = ($fnRestore -join "`n")
$bTxt = ($fnBegin -join "`n")
$iTxt = ($fnInst -join "`n")
$sTxt = ($fnStub -join "`n")

if ($pTxt -notmatch '\(void\)mprotect' -and $uTxt -notmatch '\(void\)mprotect') {
    Pass "no mprotect() result is discarded in patch_entry()/tg_hook_uninstall()"
} else { Fail "a (void)mprotect(...) is still swallowing a return value" }

if ($pTxt -match 'entry_begin_write' -and $pTxt -match 'entry_restore_prot' -and
    $pTxt -match 'g_patched = 1;' -and
    ($pTxt.IndexOf('g_patched = 1;') -lt $pTxt.IndexOf('entry_restore_prot'))) {
    Pass "patch_entry(): query -> write -> record g_patched -> checked restore"
} else { Fail "patch_entry() order/checks are not the required ones" }

if ($uTxt -match '!g_patched && !g_prot_dirty' -and
    $uTxt -match 'entry_restore_prot\("func entry \(retry\)"\)') {
    Pass "tg_hook_uninstall(): entry-already-restored still retries the protection"
} else { Fail "tg_hook_uninstall() has no retry path for a leftover RWX page" }

if ($uTxt -match 'g_patched = 0;' -and
    ($uTxt.IndexOf('g_patched = 0;') -lt $uTxt.LastIndexOf('entry_restore_prot'))) {
    Pass "tg_hook_uninstall(): g_patched reflects the entry, not the protection result"
} else { Fail "tg_hook_uninstall() sets g_patched too late (fake patched state)" }

if ($bTxt -match 'q < 0' -and $bTxt -match 'refusing to change protection' -and
    $bTxt -match 'g_entry_prot_valid = 1;') {
    Pass "entry_begin_write(): unknown protection is refused before any mprotect()"
} else { Fail "entry_begin_write() guard missing" }

if ($rTxt -match 'g_prot_dirty = 1;' -and $rTxt -notmatch 'g_entry_orig_prot =') {
    Pass "entry_restore_prot(): debt is recorded and the baseline is never rewritten"
} else { Fail "entry_restore_prot() overwrites the baseline or drops the debt" }

if ($iTxt -match 'if \(g_patched && g_thread_started && !g_prot_dirty\)') {
    Pass "tg_hook_install(): idempotent return requires the sender thread and a clean page"
} else { Fail "tg_hook_install() still returns early on g_patched alone" }

if ($sTxt -notmatch 'page_prot\(') {
    Pass "build_nlu_stub_page(): no /proc/self/maps query on the stub path"
} else { Fail "build_nlu_stub_page() still queries page_prot()" }

if ($sTxt -match 'if \(mprotect\(g_nlu_page, TG_STUB_PAGE, PROT_READ \| PROT_EXEC\) == 0\)' -and
    $sTxt -match 'g_nlu_page_degraded = 1;' -and
    $sTxt -match 'munmap') {
    Pass "build_nlu_stub_page(): RX checked -> explicit RWX fallback -> failure releases the page"
} else { Fail "build_nlu_stub_page() lifecycle not in the required shape" }

# ------------------------------------------------------------ regressions
# run_t8_061_host_tests.ps1 regenerates the T8-06.1 snippet, runs its own
# behaviour test and then the four older suites -- exactly the five requested
# regressions, so it is invoked once and its result lines are reused here.
Log ""
Log "=== regression suites (via run_t8_061_host_tests.ps1) ==="
$regRunner = Join-Path $Here "run_t8_061_host_tests.ps1"
$ErrorActionPreference = "Continue"
$regOut = & powershell -NoProfile -ExecutionPolicy Bypass -File $regRunner 2>&1 | Out-String
$regRc = $LASTEXITCODE
$ErrorActionPreference = "Stop"
($regOut.TrimEnd() -split "`r?`n") | Where-Object { $_ -match '^(PASS|FAIL)' } |
    ForEach-Object { Log ("  " + $_) }
if ($regRc -ne 0 -or $regOut -notmatch '# result: OK') {
    Fail "regression runner reported a problem (exit $regRc)"
} else {
    Pass "regression runner: # result: OK"
}

$expected = @(
    "t8_061_page_prot_test", "t8_06_switch_test", "t8_06_reprotect_test",
    "t8_05_switch_test", "t8_05_patch_test"
)
$total = 0
foreach ($name in $expected) {
    if ($regOut -match ("PASS " + [regex]::Escape($name) + ": (\d+) assertions, 0 failures")) {
        $total += [int]$Matches[1]
        Pass ("  regression " + $name + " = " + $Matches[1] + " assertions")
    } else {
        Fail ("regression suite did not pass: " + $name)
    }
}
Log ("  regression assertions total = " + $total)

Log ""
if ($script:Fail -ne 0) { Log ("# result: FAIL (" + $script:Fail + " problem(s))") }
else { Log "# result: OK (T8-06.2 behaviour test + 5 regression suites)" }
$script:Lines | Out-File -FilePath $Log -Encoding utf8
Write-Host ""
Write-Host ("log : {0}" -f $Log)
if ($script:Fail -ne 0) { exit 1 }
exit 0
