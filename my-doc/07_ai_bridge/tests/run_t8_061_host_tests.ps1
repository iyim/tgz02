# run_t8_061_host_tests.ps1 -- T8-06.1: behaviour test for page_prot() /
# nlu_pp_unprotect() / nlu_pp_reprotect(), plus the four regression suites that
# this round's change can touch.
#
#   powershell -ExecutionPolicy Bypass -File run_t8_061_host_tests.ps1
#
# The three production functions are extracted VERBATIM from
# hook_agent/libtg_hook.c into tests/out/t8_061_prod_snippet.inc and driven by
# t8_061_page_prot_test.c (fakes for fopen/mprotect, controllable g_nlu_* state).
# Every branch, including all failure paths, is executed -- the source-string
# assertions below are only a complement, never a substitute.
#
# NOTE: keep this file ASCII-only (PowerShell 5.1 reads a BOM-less file as ANSI).
$ErrorActionPreference = "Stop"

$Gcc = "C:\TDM-GCC-64\bin\gcc.exe"
if (-not (Test-Path $Gcc)) { throw "gcc not found: $Gcc" }

$Here = $PSScriptRoot
$Root = Split-Path $Here -Parent
$Android = Join-Path $Root "android"
$Ev = Join-Path $Root "evidence"
$Out = Join-Path $Here "out"
New-Item -ItemType Directory -Force $Out | Out-Null
New-Item -ItemType Directory -Force $Ev | Out-Null

$Log = Join-Path $Ev "t8_061_host_test.log"
$script:Lines = New-Object System.Collections.Generic.List[string]
function Log([string]$s) { $script:Lines.Add($s); Write-Host $s }
$script:Fail = 0
function Fail([string]$why) { $script:Fail++; Log "FAIL $why" }
function Pass([string]$why) { Log "PASS $why" }

Log "# T8-06.1 host test log (page_prot / nlu_pp_unprotect behaviour)"
Log "# host time: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
Log ""

# ---------------------------------------------------------- snippet extraction
$HookPath = Join-Path $Android "hook_agent\libtg_hook.c"
$src = Get-Content $HookPath

function Extract-Fn([string[]]$lines, [string]$sigRegex) {
    $start = -1
    for ($i = 0; $i -lt $lines.Length; $i++) {
        if ($lines[$i] -match $sigRegex) { $start = $i; break }
    }
    if ($start -lt 0) { return $null }
    $acc = @()
    for ($i = $start; $i -lt $lines.Length; $i++) {
        $acc += $lines[$i]
        if ($lines[$i] -eq '}') { break }
    }
    return $acc
}

$fnPage = Extract-Fn $src '^static int page_prot\(uintptr_t page\)$'
$fnUnp  = Extract-Fn $src '^static int nlu_pp_unprotect\(void \*ud, const char \*what,$'
$fnRep  = Extract-Fn $src '^static int nlu_pp_reprotect\(void \*ud, char \*err, size_t cap\)$'

Log "=== extract production functions from hook_agent/libtg_hook.c ==="
if ($null -eq $fnPage) { Fail "page_prot() not found in libtg_hook.c" }
if ($null -eq $fnUnp)  { Fail "nlu_pp_unprotect() not found in libtg_hook.c" }
if ($null -eq $fnRep)  { Fail "nlu_pp_reprotect() not found in libtg_hook.c" }
if ($script:Fail -ne 0) {
    $script:Lines | Out-File -FilePath $Log -Encoding utf8
    throw "extraction failed; see $Log"
}

$snippet = @()
$snippet += "/* GENERATED by run_t8_061_host_tests.ps1 -- do not edit."
$snippet += " * Verbatim copy of three functions from hook_agent/libtg_hook.c:"
$snippet += " *   page_prot(), nlu_pp_unprotect(), nlu_pp_reprotect()"
$snippet += " * Included by tests/t8_061_page_prot_test.c together with host fakes"
$snippet += " * for fopen()/mprotect() so every branch can be driven for real. */"
$snippet += ""
$snippet += $fnPage
$snippet += ""
$snippet += $fnUnp
$snippet += ""
$snippet += $fnRep
$snippet += ""
$snippet = $snippet -join "`n"
$snippetPath = Join-Path $Out "t8_061_prod_snippet.inc"
[IO.File]::WriteAllText($snippetPath, $snippet, (New-Object Text.UTF8Encoding($false)))
Log ("extracted: page_prot=" + $fnPage.Count + " lines, nlu_pp_unprotect=" + $fnUnp.Count +
     " lines, nlu_pp_reprotect=" + $fnRep.Count + " lines -> " + $snippetPath)
Pass "production functions extracted verbatim (no hand-written copy)"
Log ""

# ------------------------------------------------------- build + run new test
$Exe = Join-Path $Out "t8_061_page_prot_test.exe"
$SrcFile = Join-Path $Here "t8_061_page_prot_test.c"
$Argv = @("-O2", "-Wall", "-Wextra", "-std=gnu99", "-I", $Here, "-o", $Exe, $SrcFile)

Log "=== build t8_061_page_prot_test ==="
Log ("gcc " + ($Argv -join " "))
$build = & $Gcc @Argv 2>&1 | Out-String
$brc = $LASTEXITCODE
if ($build.Trim().Length -gt 0) { ($build.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ } }
else { Log "(no compiler output: 0 warning, 0 error)" }
if ($brc -ne 0) { Fail "build failed: t8_061_page_prot_test" }
elseif ($build -match 'warning\s*:') { Fail "compiler warnings in t8_061_page_prot_test" }
else { Pass "t8_061_page_prot_test: 0 warning / 0 error" }

Log ""
Log "=== run t8_061_page_prot_test ==="
$run = & $Exe 2>&1 | Out-String
$rrc = $LASTEXITCODE
($run.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ }
Log ("exit : " + $rrc)
if ($run -notmatch 'pass=(\d+) fail=(\d+)') { Fail "t8_061_page_prot_test: unreadable summary" }
elseif ([int]$Matches[2] -ne 0) { Fail ("t8_061_page_prot_test: " + $Matches[2] + " failing assertion(s)") }
elseif ($rrc -ne 0) { Fail "t8_061_page_prot_test: non-zero exit" }
else { Pass ("t8_061_page_prot_test: " + $Matches[1] + " assertions, 0 failures") }
Log ""

# --------------------------------- complement: the extracted text is the fix
Log "=== source assertions (only as a complement to the behaviour test) ==="
if ($fnPage -match 'return -1;' -and ($fnPage -join "`n") -notmatch 'return 7;') {
    Pass "page_prot(): unknown page / unreadable maps -> -1 (old 'return 7' is gone)"
} else { Fail "page_prot() still returns the old 7 sentinel" }

if (($fnUnp -join "`n") -match 'original_prot < 0' -and ($fnUnp -join "`n") -match 'refusing to change protection') {
    Pass "nlu_pp_unprotect(): refuses to change protection when the baseline is unknown"
} else { Fail "nlu_pp_unprotect() guard missing" }

if (($fnUnp -join "`n") -match 'g_nlu_prot_valid = 1;' -and
    (($fnUnp -join "`n") -notmatch '(?s)page_prot\(page\);\s*g_nlu_orig_prot = ') ) {
    Pass "baseline is marked valid only after the query succeeded"
} else { Fail "baseline validity handling not in the required order" }

# ------------------------------------------------------------ regressions
$Cases = @(
    @{ name = "t8_06_switch_test";    src = @("t8_06_switch_test.c", "nlu_switch.c") },
    @{ name = "t8_06_reprotect_test"; src = @("t8_06_reprotect_test.c", "nlu_patch.c") },
    @{ name = "t8_05_switch_test";    src = @("t8_05_switch_test.c", "nlu_switch.c") },
    @{ name = "t8_05_patch_test";     src = @("t8_05_patch_test.c", "nlu_patch.c") }
)

Log ""
Log "=== regression suites ==="
foreach ($c in $Cases) {
    $e = Join-Path $Out ($c.name + ".exe")
    $s = @()
    foreach ($f in $c.src) {
        if (Test-Path (Join-Path $Here $f)) { $s += (Join-Path $Here $f) }
        else { $s += (Join-Path $Android $f) }
    }
    $a = @("-O2", "-Wall", "-Wextra", "-std=gnu99", "-pthread", "-I", $Android, "-o", $e) + $s
    $bo = & $Gcc @a 2>&1 | Out-String
    $br = $LASTEXITCODE
    if ($br -ne 0) {
        ($bo.TrimEnd() -split "`r?`n") | ForEach-Object { Log $_ }
        Fail ("build failed: " + $c.name)
        continue
    }
    if ($bo -match 'warning\s*:') { Fail ("compiler warnings in " + $c.name) }
    $ro = & $e 2>&1 | Out-String
    $rr = $LASTEXITCODE
    ($ro.TrimEnd() -split "`r?`n") | Where-Object { $_ -match 'RESULT|FAIL' } | ForEach-Object { Log ("  " + $_) }
    if ($ro -notmatch 'pass=(\d+) fail=(\d+)') { Fail ($c.name + ": unreadable summary") }
    elseif ([int]$Matches[2] -ne 0) { Fail ($c.name + ": " + $Matches[2] + " failing assertion(s)") }
    elseif ($rr -ne 0) { Fail ($c.name + ": non-zero exit") }
    else { Pass ($c.name + ": " + $Matches[1] + " assertions, 0 failures") }
}

Log ""
if ($script:Fail -ne 0) { Log ("# result: FAIL (" + $script:Fail + " problem(s))") }
else { Log "# result: OK (T8-06.1 behaviour test + 4 regression suites)" }
$script:Lines | Out-File -FilePath $Log -Encoding utf8
Write-Host ""
Write-Host ("log : {0}" -f $Log)
if ($script:Fail -ne 0) { exit 1 }
exit 0
